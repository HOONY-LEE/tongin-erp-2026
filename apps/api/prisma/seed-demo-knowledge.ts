async function main() {
  for (const d of DOCS) {
    if (await prisma.knowledgeDoc.findFirst({ where: { title: d.title } })) {
      console.log(`지식베이스 '${d.title}' — 이미 있음(건너뜀)`);
      continue;
    }
    await prisma.$transaction(async (tx) => {
      const doc = await tx.knowledgeDoc.create({
        data: {
          title: d.title,
          category: d.category,
          content: d.content,
          summary: d.summary,
          keywords: d.keywords,
          analyzeStatus: 'DONE',
          analyzedAt: new Date(),
          updatedByName: '시스템',
        },
      });
      const ids = new Map<string, string>();
      for (const [name, kind, description] of d.concepts) {
        const c =
          (await tx.knowledgeConcept.findUnique({ where: { name } })) ??
          (await tx.knowledgeConcept.create({ data: { name, kind, description } }));
        ids.set(name, c.id);
        await tx.knowledgeMention.create({ data: { docId: doc.id, conceptId: c.id } });
      }
      for (const [from, label, to] of d.relations) {
        const f = ids.get(from);
        const t = ids.get(to);
        if (f && t)
          await tx.knowledgeRelation.create({ data: { docId: doc.id, fromId: f, toId: t, label } });
      }
    });
    console.log(`지식베이스 '${d.title}' 넣음`);
  }
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
